//! The review page: tabs of terminal windows in the terminal's font and
//! colours, with ANSI styling rendered.

/// Ghostty's defaults, as the terminal shows them: JetBrains Mono at 13 pt,
/// white on #282c34, ligatures off, and its 16-colour palette.
const FONT: &str = "'JetBrains Mono', monospace";
const BACKGROUND: &str = "#282c34";
const FOREGROUND: &str = "#ffffff";
const PALETTE: [&str; 16] = [
    "#1d1f21", "#cc6666", "#b5bd68", "#f0c674", "#81a2be", "#b294bb", "#8abeb7", "#c5c8c6", "#666666", "#d54e53",
    "#b9ca4a", "#e7c547", "#7aa6da", "#c397d8", "#70c0b1", "#eaeaea",
];

/// One printout, as the terminal shows it.
pub struct Case {
    pub title: &'static str,
    pub about: &'static str,
    /// The command typed, shown as a prompt above the output.
    pub command: Option<String>,
    pub text: String,
}

impl Case {
    pub fn new(title: &'static str, about: &'static str, text: String) -> Self {
        Self { title, about, command: None, text }
    }
}

/// A sub-tab: one command or one kind of run.
pub struct Group {
    pub title: &'static str,
    pub about: &'static str,
    pub cases: Vec<Case>,
}

/// A top tab: one frontend.
pub struct Tab {
    pub title: &'static str,
    pub about: &'static str,
    pub groups: Vec<Group>,
}

pub fn render(tabs: &[Tab]) -> String {
    let mut nav = String::new();
    let mut panels = String::new();
    for tab in tabs {
        let first = format!("{}-{}", slug(tab.title), slug(tab.groups[0].title));
        nav.push_str(&format!("<a class=\"tab\" data-tab=\"{}\" href=\"#{first}\">{}</a>", slug(tab.title), escape(tab.title)));
        let mut groups = String::new();
        let mut subnav = String::new();
        for group in &tab.groups {
            let id = format!("{}-{}", slug(tab.title), slug(group.title));
            subnav.push_str(&format!("<a class=\"subtab\" href=\"#{id}\">{}</a>", escape(group.title)));
            groups.push_str(&format!("<section class=\"group\" id=\"{id}\">\n<p class=\"about\">{}</p>\n", escape(group.about)));
            for case in &group.cases {
                groups.push_str(&format!("<h3>{}</h3>\n<p>{}</p>\n<pre class=\"terminal\">", escape(case.title), escape(case.about)));
                if let Some(command) = &case.command {
                    groups.push_str(&format!("<span class=\"prompt\">$ </span>{}\n", escape(command)));
                }
                groups.push_str(&ansi(&case.text));
                groups.push_str("</pre>\n");
            }
            groups.push_str("</section>\n");
        }
        let subnav = if tab.groups.len() > 1 { format!("<nav class=\"subtabs\">{subnav}</nav>\n") } else { String::new() };
        panels.push_str(&format!(
            "<div class=\"panel\" data-tab=\"{}\">\n<p class=\"about\">{}</p>\n{subnav}{groups}</div>\n",
            slug(tab.title),
            escape(tab.about)
        ));
    }
    format!(
        r##"<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Printouts</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=JetBrains+Mono:ital,wght@0,400;0,700;1,400;1,700&display=swap">
<style>
  body {{ margin: 0 auto; max-width: 1100px; padding: 24px 16px 64px; background: #f6f6f4; color: #1d1f21;
         font: 15px/1.5 -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; }}
  h1 {{ font-size: 24px; margin: 0 0 4px; }}
  h3 {{ font-size: 15px; margin: 24px 0 0; }}
  p {{ margin: 2px 0 8px; color: #55585c; }}
  nav {{ display: flex; flex-wrap: wrap; gap: 4px; }}
  .tabs {{ margin: 20px 0 12px; border-bottom: 1px solid #d6d6d2; }}
  .tab, .subtab {{ text-decoration: none; color: #55585c; padding: 6px 14px; border-radius: 6px 6px 0 0; }}
  .tab {{ font-weight: 600; font-size: 16px; }}
  .tab.on {{ color: #1d1f21; background: #e8e8e4; }}
  .subtabs {{ margin: 8px 0 4px; }}
  .subtab {{ border-radius: 999px; font-family: {FONT}; font-size: 13px; background: #ecece8; }}
  .subtab.on {{ background: {BACKGROUND}; color: {FOREGROUND}; }}
  .panel, .group {{ display: none; }}
  .panel.on, .group.on {{ display: block; }}
  .terminal {{ margin: 0; padding: 10px 12px; overflow-x: auto; border-radius: 6px;
              background: {BACKGROUND}; color: {FOREGROUND}; font-family: {FONT}; font-size: 13px;
              line-height: 1.3; tab-size: 8; white-space: pre;
              font-variant-ligatures: none; font-feature-settings: "calt" 0, "liga" 0, "dlig" 0; }}
  .prompt {{ color: {prompt}; }}
</style>
</head>
<body>
<h1>Printouts</h1>
<p>Every standard case, as the terminal shows it. Generated by <code>cargo review-printouts</code>.</p>
<nav class="tabs">{nav}</nav>
{panels}<script>
  function show() {{
    var id = location.hash.slice(1);
    var group = document.getElementById(id) || document.querySelector(".group");
    var panel = group.closest(".panel");
    document.querySelectorAll(".panel, .group, .tab, .subtab").forEach(function (node) {{ node.classList.remove("on"); }});
    panel.classList.add("on");
    group.classList.add("on");
    document.querySelector('.tab[data-tab="' + panel.dataset.tab + '"]').classList.add("on");
    var sub = document.querySelector('.subtab[href="#' + group.id + '"]');
    if (sub) sub.classList.add("on");
  }}
  window.addEventListener("hashchange", show);
  show();
</script>
</body>
</html>
"##,
        prompt = PALETTE[8],
    )
}

/// `text` as HTML, its SGR escapes as styled spans. Panics on any other
/// escape, which this page would show wrongly.
fn ansi(text: &str) -> String {
    let mut html = String::new();
    let mut style = Style::default();
    let mut rest = text;
    while let Some(at) = rest.find('\x1b') {
        html.push_str(&style.wrap(&escape(&rest[..at])));
        let sequence = &rest[at..];
        let end = sequence.find('m').filter(|_| sequence.starts_with("\x1b[")).unwrap_or_else(|| {
            panic!("only SGR escapes are rendered: {:?}", &sequence[..sequence.len().min(8)])
        });
        style.apply(&sequence[2..end]);
        rest = &sequence[end + 1..];
    }
    html.push_str(&style.wrap(&escape(rest)));
    html
}

#[derive(Default)]
struct Style {
    bold: bool,
    dim: bool,
    italic: bool,
    underline: bool,
    foreground: Option<usize>,
    background: Option<usize>,
}

impl Style {
    fn apply(&mut self, parameters: &str) {
        for code in parameters.split(';').map(|code| code.parse::<usize>().unwrap_or(0)) {
            match code {
                0 => *self = Self::default(),
                1 => self.bold = true,
                2 => self.dim = true,
                3 => self.italic = true,
                4 => self.underline = true,
                22 => (self.bold, self.dim) = (false, false),
                23 => self.italic = false,
                24 => self.underline = false,
                30..=37 => self.foreground = Some(code - 30),
                39 => self.foreground = None,
                40..=47 => self.background = Some(code - 40),
                49 => self.background = None,
                90..=97 => self.foreground = Some(code - 90 + 8),
                100..=107 => self.background = Some(code - 100 + 8),
                _ => panic!("SGR {code} is not rendered"),
            }
        }
    }

    fn wrap(&self, text: &str) -> String {
        let mut css = String::new();
        if self.bold {
            css.push_str("font-weight:700;");
        }
        if self.dim {
            css.push_str("opacity:0.6;");
        }
        if self.italic {
            css.push_str("font-style:italic;");
        }
        if self.underline {
            css.push_str("text-decoration:underline;");
        }
        if let Some(colour) = self.foreground {
            css.push_str(&format!("color:{};", PALETTE[colour]));
        }
        if let Some(colour) = self.background {
            css.push_str(&format!("background:{};", PALETTE[colour]));
        }
        if css.is_empty() || text.is_empty() { text.to_owned() } else { format!("<span style=\"{css}\">{text}</span>") }
    }
}

fn slug(text: &str) -> String {
    text.to_lowercase()
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .collect::<Vec<_>>()
        .join("-")
}

fn escape(text: &str) -> String {
    text.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}
